def main():
    # ======================
    # EXP1 (classification): read exp1_summary.csv
    # ======================
    if EXP1_CSV.exists():
        exp1 = pd.read_csv(EXP1_CSV)
        # expect columns like: branch, run, rank, ar, val_acc, test_acc ...
        # If your CSV differs, adjust mapping here.
        # Try to normalize:
        colmap = {c.lower(): c for c in exp1.columns}
        # required
        for need in ["branch", "run"]:
            if need not in colmap:
                # guess from existing
                pass

        # build normalized frame
        def pick(name, default=None):
            return exp1[colmap[name]] if name in colmap else default

        # tolerate different naming
        def getcol(*names):
            for n in names:
                if n in colmap:
                    return exp1[colmap[n]]
            return None

        exp1_norm = pd.DataFrame({
            "branch": getcol("branch", "type"),
            "run": getcol("run", "name"),
            "rank": getcol("rank", "r"),
            "ar": getcol("ar", "alpha_over_r"),
            "val_acc": getcol("val_acc", "val_accuracy"),
            "test_acc": getcol("test_acc", "test_accuracy"),
        })

        exp1_norm["rank"] = pd.to_numeric(exp1_norm["rank"], errors="coerce")
        exp1_norm["ar"] = pd.to_numeric(exp1_norm["ar"], errors="coerce")
        exp1_norm["val_acc"] = pd.to_numeric(exp1_norm["val_acc"], errors="coerce")
        exp1_norm["test_acc"] = pd.to_numeric(exp1_norm["test_acc"], errors="coerce")

        # split
        exp1_lora = exp1_norm[exp1_norm["branch"].str.contains("lora", case=False, na=False)].copy()
        exp1_eora = exp1_norm[exp1_norm["branch"].str.contains("eora", case=False, na=False)].copy()

        # heatmaps
        _pivot_heatmap(exp1_lora, "test_acc", "EXP1 LoRA: Test Accuracy heatmap (rank vs ar)", REPORT_DIR / "exp1_lora_testacc_heatmap.png")
        _pivot_heatmap(exp1_eora, "test_acc", "EXP1 EoRA: Test Accuracy heatmap (rank vs ar)", REPORT_DIR / "exp1_eora_testacc_heatmap.png")

        # best over rank curves
        _line_best_over_rank(exp1_lora, "test_acc", "EXP1 LoRA: best test_acc per rank", REPORT_DIR / "exp1_lora_best_over_rank.png")
        _line_best_over_rank(exp1_eora, "test_acc", "EXP1 EoRA: best test_acc per rank", REPORT_DIR / "exp1_eora_best_over_rank.png")

        # best compare bar
        best_lora = _best_by(exp1_lora, "test_acc", higher_is_better=True)
        best_eora = _best_by(exp1_eora, "test_acc", higher_is_better=True)
        _bar_best_compare(best_lora, best_eora, "test_acc", "EXP1: Best test_acc (LoRA vs EoRA)", REPORT_DIR / "exp1_best_testacc_bar.png")

        # save a clean exp1 table
        exp1_norm.to_csv(REPORT_DIR / "exp1_runs_clean.csv", index=False)

    # ======================
    # EXP2 (output matching): scan metrics.json
    # ======================
    exp2_lora = _scan_exp2_runs(EXP2_LORA_DIR, "LoRA")
    exp2_eora = _scan_exp2_runs(EXP2_EORA_DIR, "EoRA")
    exp2 = pd.concat([exp2_lora, exp2_eora], ignore_index=True)

    if not exp2.empty:
        exp2.to_csv(REPORT_DIR / "exp2_summary.csv", index=False)

        # scatter KL-MSE with acc color
        _scatter_kl_mse_acc(exp2_lora, "EXP2 LoRA: (KL, MSE) with Accuracy color", REPORT_DIR / "exp2_lora_scatter_kl_mse_acc.png")
        _scatter_kl_mse_acc(exp2_eora, "EXP2 EoRA: (KL, MSE) with Accuracy color", REPORT_DIR / "exp2_eora_scatter_kl_mse_acc.png")

        # KL heatmap (rank vs ar), per branch
        def hm(df, metric, name):
            _pivot_heatmap(df.rename(columns={"test_kl": metric}), metric,
                           f"EXP2 {name}: {metric} heatmap (rank vs ar)", REPORT_DIR / f"exp2_{name.lower()}_{metric}_heatmap.png")

        # easier: reuse pivot function but pass correct column
        _pivot_heatmap(exp2_lora.rename(columns={"test_kl": "KL"}), "KL", "EXP2 LoRA: Test KL heatmap (rank vs ar)", REPORT_DIR / "exp2_lora_testkl_heatmap.png")
