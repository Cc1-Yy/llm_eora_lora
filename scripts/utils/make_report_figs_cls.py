# ---------- helpers ----------
def _safe_float(x, default=np.nan):
    try:
        return float(x)
    except Exception:
        return default

def _read_json(path: Path) -> Optional[Dict[str, Any]]:
    try:
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    except Exception:
        return None

def _parse_run_name(run_name: str) -> Dict[str, Any]:
    """
    exp run folder names like:
      r16_ar4
      r64_ar1.25_T1
    """
    out = {"rank": np.nan, "ar": np.nan, "T": np.nan}
    m = re.search(r"r(\d+)", run_name)
    if m:
        out["rank"] = int(m.group(1))
    m = re.search(r"ar([0-9.]+)", run_name)
    if m:
        out["ar"] = float(m.group(1))
    m = re.search(r"_T([0-9.]+)", run_name)
    if m:
        out["T"] = float(m.group(1))
    return out

def _scan_exp2_runs(root: Path, tag: str) -> pd.DataFrame:
    """
    Scan outputs/exp2_lora/*/metrics.json and outputs/exp2_eora/*/metrics.json
    Expect metrics.json like:
      {"val": {...}, "test.py": {...}, "config": {...}}  OR your own layout.
    We'll be robust and try common keys.
    """
    rows = []
    if not root.exists():
        return pd.DataFrame()

    for run_dir in sorted([p for p in root.iterdir() if p.is_dir()]):
        metrics_path = run_dir / "metrics.json"
        j = _read_json(metrics_path)
        if j is None:
            # try fallback: any json file
            cand = list(run_dir.glob("*.json"))
            if cand:
                j = _read_json(cand[0])
        if j is None:
            continue

        meta = _parse_run_name(run_dir.name)

        # try to find test.py dict
        test = j.get("test.py", j.get("Test", j.get("metrics_test", j)))
        val = j.get("val", j.get("Val", j.get("metrics_val", {})))

        row = {
            "branch": tag,
            "run": run_dir.name,
            "rank": meta["rank"],
            "ar": meta["ar"],
            "T": meta["T"],
            # metrics (robust keys)
            "test_acc": _safe_float(test.get("accuracy", test.get("acc", np.nan))),
            "test_ce": _safe_float(test.get("ce_loss", test.get("loss", np.nan))),
            "test_kl": _safe_float(test.get("kl_to_teacher", test.get("kl", np.nan))),
            "test_mse": _safe_float(test.get("mse_logits_to_teacher", test.get("mse", np.nan))),
            "val_acc": _safe_float(val.get("accuracy", val.get("acc", np.nan))),
            "val_ce": _safe_float(val.get("ce_loss", val.get("loss", np.nan))),
            "val_kl": _safe_float(val.get("kl_to_teacher", val.get("kl", np.nan))),
            "val_mse": _safe_float(val.get("mse_logits_to_teacher", val.get("mse", np.nan))),
            "metrics_path": str(metrics_path),
        }
        rows.append(row)

    return pd.DataFrame(rows)

def _pivot_heatmap(df: pd.DataFrame, value_col: str, title: str, out_png: Path):
    """
    Heatmap of value_col over (rank, ar). One branch at a time.
    """
    if df.empty:
        return

    p = df.pivot_table(index="rank", columns="ar", values=value_col, aggfunc="max")
    p = p.sort_index().sort_index(axis=1)

    fig = plt.figure(figsize=(10, 4))
    ax = plt.gca()
    im = ax.imshow(p.values, aspect="auto")
    ax.set_title(title)
    ax.set_xlabel("alpha/r (ar)")
    ax.set_ylabel("rank (r)")

    ax.set_xticks(range(len(p.columns)))
    ax.set_xticklabels([str(c) for c in p.columns])
    ax.set_yticks(range(len(p.index)))
    ax.set_yticklabels([str(i) for i in p.index])

    plt.colorbar(im, ax=ax)
    plt.tight_layout()
    plt.savefig(out_png, dpi=200)
    plt.close(fig)

def _best_by(df: pd.DataFrame, sort_key: str, higher_is_better: bool = True) -> pd.DataFrame:
    if df.empty:
        return df
    df2 = df.copy()
    df2 = df2.dropna(subset=[sort_key])
    df2 = df2.sort_values(sort_key, ascending=not higher_is_better)
    return df2.head(1)

def _line_best_over_rank(df: pd.DataFrame, value_col: str, title: str, out_png: Path):
    """
    For each rank: take best over ar, then plot vs rank.
    """
    if df.empty:
        return
    g = df.dropna(subset=["rank", value_col]).groupby("rank")[value_col].max().reset_index()
    g = g.sort_values("rank")

    fig = plt.figure(figsize=(6, 4))
    ax = plt.gca()
    ax.plot(g["rank"], g[value_col], marker="o")
    ax.set_title(title)
    ax.set_xlabel("rank (r)")
    ax.set_ylabel(value_col)
    ax.grid(True, alpha=0.3)
    plt.tight_layout()
    plt.savefig(out_png, dpi=200)
    plt.close(fig)

def _scatter_kl_mse_acc(df: pd.DataFrame, title: str, out_png: Path):
    """
    Scatter: x=KL, y=MSE, point size by Acc (or color by Acc).
    """
    if df.empty:
        return
    d = df.dropna(subset=["test_kl", "test_mse", "test_acc"]).copy()
    if d.empty:
        return

    fig = plt.figure(figsize=(7, 5))
    ax = plt.gca()
    sc = ax.scatter(d["test_kl"], d["test_mse"], c=d["test_acc"], s=60, alpha=0.85)
    ax.set_title(title)
    ax.set_xlabel("Test KL to teacher (lower better)")
    ax.set_ylabel("Test MSE logits to teacher (lower better)")
    cb = plt.colorbar(sc, ax=ax)
    cb.set_label("Test accuracy (higher better)")
    ax.grid(True, alpha=0.25)
    plt.tight_layout()
    plt.savefig(out_png, dpi=200)
    plt.close(fig)

def _bar_best_compare(best_a: pd.DataFrame, best_b: pd.DataFrame, metric: str, title: str, out_png: Path):
    if best_a.empty or best_b.empty:
        return
    labels = [best_a.iloc[0]["branch"], best_b.iloc[0]["branch"]]
    values = [best_a.iloc[0][metric], best_b.iloc[0][metric]]

    fig = plt.figure(figsize=(5, 4))
    ax = plt.gca()
    ax.bar(labels, values)
    ax.set_title(title)
    ax.set_ylabel(metric)
    for i, v in enumerate(values):
        ax.text(i, v, f"{v:.4f}", ha="center", va="bottom")
    plt.tight_layout()
    plt.savefig(out_png, dpi=200)
    plt.close(fig)

