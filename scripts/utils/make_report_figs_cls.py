        best_lora_acc = _best_by(exp2_lora, "test_acc", higher_is_better=True)
        best_eora_acc = _best_by(exp2_eora, "test_acc", higher_is_better=True)
        _bar_best_compare(best_lora_acc, best_eora_acc, "test_acc", "EXP2: Best test_acc (LoRA vs EoRA)", REPORT_DIR / "exp2_best_testacc_bar.png")

        best_lora_kl = _best_by(exp2_lora, "test_kl", higher_is_better=False)
        best_eora_kl = _best_by(exp2_eora, "test_kl", higher_is_better=False)
        _bar_best_compare(best_lora_kl, best_eora_kl, "test_kl", "EXP2: Best (lowest) test_kl (LoRA vs EoRA)", REPORT_DIR / "exp2_best_testkl_bar.png")

